#!/usr/bin/env bash
# Maintainer flow: regenerate private/requirements_lock.txt, the hash-pinned
# lock behind @rules_temporal_pypi (the built-in history replay runner).
#
#   1. Edit private/requirements.in (e.g. bump the temporalio pin).
#   2. tools/update_replay_requirements.sh
#   3. Update the pinned version in README.md / DESIGN.md / CLAUDE.md and run
#      bazel test //tests/... .
#
# The lock is universal (environment markers, not one host) and lists the
# sha256 of every published wheel, so the same file serves linux
# x86_64/aarch64 and macOS x86_64/arm64. --only-binary keeps sdists out:
# temporalio (Rust core) and protobuf (upb) are C extensions, and building
# them from source inside a repository rule is not something we support.
#
# Needs `uv` (https://docs.astral.sh/uv/) on PATH, or set UV=/path/to/uv.
set -euo pipefail

repo="$(cd "$(dirname "$0")/.." && pwd)"
uv="${UV:-uv}"
command -v "$uv" >/dev/null 2>&1 || {
    echo "update_replay_requirements: uv not found (install it, or set UV=)" >&2
    exit 1
}
# Keep in step with python_version in MODULE.bazel (python.toolchain /
# pip.parse) and REPLAY_PYTHON_VERSION in private/replay.bzl.
python_version="3.12"

cd "$repo"
"$uv" pip compile \
    --universal \
    --generate-hashes \
    --only-binary :all: \
    --python-version "$python_version" \
    --no-header \
    --upgrade \
    private/requirements.in \
    -o private/requirements_lock.txt.new
{
    echo "# Generated by tools/update_replay_requirements.sh from private/requirements.in"
    echo "# (uv pip compile --universal --generate-hashes --only-binary :all:"
    echo "#  --python-version $python_version). Do not edit by hand."
    cat private/requirements_lock.txt.new
} > private/requirements_lock.txt
rm -f private/requirements_lock.txt.new
echo "wrote private/requirements_lock.txt:"
grep -E '^[A-Za-z0-9_.-]+==' private/requirements_lock.txt | sed 's/ \\$//; s/^/  /'
